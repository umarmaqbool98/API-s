CREATE TABLE IF NOT EXISTS students (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no varchar(20) NOT NULL UNIQUE,
    full_name varchar(100) NOT NULL,
    email varchar(150) NOT NULL UNIQUE,
    created_at_utc timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_students_email_lowercase CHECK (email = lower(email))
);

CREATE TABLE IF NOT EXISTS courses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(10) NOT NULL UNIQUE,
    title varchar(150) NOT NULL,
    credit_hours integer NOT NULL CHECK (credit_hours BETWEEN 1 AND 4),
    created_at_utc timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS enrollments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    mark integer NULL CHECK (mark IS NULL OR (mark >= 0 AND mark <= 100)),
    enrolled_at_utc timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_enrollment UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('Teacher', 'Student')),
    student_id integer NULL REFERENCES students(id) ON DELETE SET NULL
);
